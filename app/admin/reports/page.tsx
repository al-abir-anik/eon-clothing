function formatMoney(value: number) {
  return `৳${value.toLocaleString("en-BD", {
    maximumFractionDigits: 0,
  })}`;
}

function formatDate(date: string) {
  const parsed = new Date(`${date}T00:00:00`);

  return parsed.toLocaleDateString("en-BD", {
    day: "numeric",
    month: "short",
    year: "numeric",
  });
}

function formatExpenseCategory(category: string) {
  const labels: Record<string, string> = {
    advertising: "Advertising",
    packaging: "Packaging",
    payment_gateway: "Payment Gateway",
    platform: "Platform / Software",
    salary: "Salary / Labor",
    refund_return: "Refund / Return",
    courier: "Courier / Shipping",
    other: "Other",
  };

  return (
    labels[category] ??
    category
      .replace(/_/g, " ")
      .replace(/\b\w/g, (letter) => letter.toUpperCase())
  );
}

type ReportMetricProps = {
  label: string;
  value: string;
  icon: React.ReactNode;
  accent?: "default" | "positive" | "negative" | "warning";
};

function ReportMetric({
  label,
  value,
  icon,
  accent = "default",
}: ReportMetricProps) {
  const accentClass = {
    default: "text-neutral-500",
    positive: "text-emerald-600",
    negative: "text-red-600",
    warning: "text-amber-600",
  }[accent];

  return (
    <div className="border border-neutral-200 bg-white p-5">
      <div className="flex items-start justify-between gap-4">
        <p className="text-xs font-medium uppercase tracking-wide text-neutral-400">
          {label}
        </p>

        <span className={accentClass}>{icon}</span>
      </div>

      <p className="mt-3 text-2xl font-semibold tracking-tight text-neutral-950">
        {value}
      </p>
    </div>
  );
}

function ReportRow({
  label,
  value,
  strong = false,
  negative = false,
  positive = false,
}: {
  label: string;
  value: string;
  strong?: boolean;
  negative?: boolean;
  positive?: boolean;
}) {
  let valueClass = "text-neutral-950";

  if (negative) {
    valueClass = "text-red-600";
  }

  if (positive) {
    valueClass = "text-emerald-600";
  }

  return (
    <div className="flex items-center justify-between gap-6 py-3">
      <span
        className={
          strong
            ? "text-sm font-semibold text-neutral-950"
            : "text-sm text-neutral-600"
        }
      >
        {label}
      </span>

      <span
        className={`text-sm ${
          strong ? "font-semibold" : "font-medium"
        } ${valueClass}`}
      >
        {value}
      </span>
    </div>
  );
}

function ProductTable({
  products,
  totalRevenue,
}: {
  products: AnalyticsProductSales[];
  totalRevenue: number;
}) {
  if (products.length === 0) {
    return (
      <div className="border border-neutral-200 bg-white p-6">
        <h2 className="text-base font-semibold text-neutral-950">
          Product Sales
        </h2>

        <div className="flex min-h-[180px] items-center justify-center">
          <div className="text-center">
            <p className="text-sm font-medium text-neutral-700">
              No product sales
            </p>

            <p className="mt-1 text-sm text-neutral-500">
              Completed product sales will appear here.
            </p>
          </div>
        </div>
      </div>
    );
  }

  return (
    <div className="border border-neutral-200 bg-white">
      <div className="border-b border-neutral-200 p-6">
        <h2 className="text-base font-semibold text-neutral-950">
          Product Sales
        </h2>

        <p className="mt-1 text-sm text-neutral-500">
          Product-level sales generated by completed orders.
        </p>
      </div>

      <div className="overflow-x-auto">
        <table className="w-full min-w-[720px] text-sm">
          <thead>
            <tr className="border-b border-neutral-200 bg-neutral-50 text-left">
              <th className="px-6 py-3 font-medium text-neutral-500">
                Product
              </th>

              <th className="px-6 py-3 font-medium text-neutral-500">SKU</th>

              <th className="px-6 py-3 text-right font-medium text-neutral-500">
                Units
              </th>

              <th className="px-6 py-3 text-right font-medium text-neutral-500">
                Revenue
              </th>

              <th className="px-6 py-3 text-right font-medium text-neutral-500">
                Share
              </th>
            </tr>
          </thead>

          <tbody>
            {products.map((product) => {
              const share =
                totalRevenue > 0 ? (product.revenue / totalRevenue) * 100 : 0;

              return (
                <tr
                  key={product.productId}
                  className="border-b border-neutral-100 last:border-0"
                >
                  <td className="px-6 py-4">
                    <p className="font-medium text-neutral-950">
                      {product.name}
                    </p>
                  </td>

                  <td className="px-6 py-4 text-neutral-500">
                    {product.sku || "—"}
                  </td>

                  <td className="px-6 py-4 text-right font-medium text-neutral-950">
                    {product.unitsSold.toLocaleString("en-BD")}
                  </td>

                  <td className="px-6 py-4 text-right font-medium text-neutral-950">
                    {formatMoney(product.revenue)}
                  </td>

                  <td className="px-6 py-4 text-right text-neutral-500">
                    {share.toFixed(1)}%
                  </td>
                </tr>
              );
            })}
          </tbody>
        </table>
      </div>
    </div>
  );
}

function ExpenseTable({
  expenses,
}: {
  expenses: {
    category: string;
    amount: number;
  }[];
}) {
  if (expenses.length === 0) {
    return (
      <div className="border border-neutral-200 bg-white p-6">
        <h2 className="text-base font-semibold text-neutral-950">
          Operating Expenses
        </h2>

        <p className="mt-4 text-sm text-neutral-500">
          No operating expenses recorded for this period.
        </p>
      </div>
    );
  }

  const total = expenses.reduce((sum, expense) => sum + expense.amount, 0);

  return (
    <div className="border border-neutral-200 bg-white p-6">
      <h2 className="text-base font-semibold text-neutral-950">
        Operating Expenses
      </h2>

      <p className="mt-1 text-sm text-neutral-500">
        Recorded business expenses excluding product COGS.
      </p>

      <div className="mt-5">
        {expenses.map((expense) => (
          <ReportRow
            key={expense.category}
            label={formatExpenseCategory(expense.category)}
            value={formatMoney(expense.amount)}
          />
        ))}

        <div className="mt-2 border-t border-neutral-200 pt-2">
          <ReportRow
            label="Total Operating Expenses"
            value={formatMoney(total)}
            strong
          />
        </div>
      </div>
    </div>
  );
}

export default async function AdminReportsPage({
  searchParams,
}: {
  searchParams: Promise<{
    from?: string;
    to?: string;
  }>;
}) {
  const params = await searchParams;

  const now = new Date();

  const today = new Date(now.getFullYear(), now.getMonth(), now.getDate());

  const defaultFrom = new Date(today);
  defaultFrom.setDate(defaultFrom.getDate() - 29);

  const formatQueryDate = (date: Date) => {
    const year = date.getFullYear();
    const month = String(date.getMonth() + 1).padStart(2, "0");
    const day = String(date.getDate()).padStart(2, "0");

    return `${year}-${month}-${day}`;
  };

  const from = params.from ?? formatQueryDate(defaultFrom);
  const to = params.to ?? formatQueryDate(today);

  const report = await getAnalyticsSummary({
    from,
    to,
  });

  const profitMargin =
    report.revenue > 0 ? (report.profit / report.revenue) * 100 : 0;

  return (
    <section>
      {/* Header */}
      <div className="flex flex-col gap-5 lg:flex-row lg:items-end lg:justify-between">
        <div>
          <p className="text-xs font-medium uppercase tracking-[0.18em] text-neutral-500">
            Reports
          </p>

          <h1 className="mt-2 text-3xl font-semibold tracking-tight text-neutral-950">
            Sales Report
          </h1>

          <p className="mt-2 text-sm text-neutral-500">
            Detailed financial and product sales report.
          </p>

          <p className="mt-3 text-xs font-medium text-neutral-400">
            {formatDate(from)} — {formatDate(to)}
          </p>
        </div>

        <div className="flex flex-wrap items-center gap-2 print:hidden">
          <PrintButton />

          <ExportButton products={report.topProducts} from={from} to={to} />
        </div>
      </div>

      <DateRangeSelector initialFrom={from} initialTo={to} />

      {/* Summary */}
      <div className="mt-8 grid gap-4 sm:grid-cols-2 lg:grid-cols-4">
        <ReportMetric
          label="Gross Sales"
          value={formatMoney(report.grossSales)}
          icon={<CircleDollarSign size={18} strokeWidth={1.8} />}
        />

        <ReportMetric
          label="Discounts"
          value={formatMoney(report.discountAmount)}
          icon={<Percent size={18} strokeWidth={1.8} />}
          accent="warning"
        />

        <ReportMetric
          label="Net Sales"
          value={formatMoney(report.netSales)}
          icon={<Wallet size={18} strokeWidth={1.8} />}
        />

        <ReportMetric
          label="Revenue"
          value={formatMoney(report.revenue)}
          icon={<BarChart3 size={18} strokeWidth={1.8} />}
          accent="positive"
        />
      </div>

      {/* Cost + profit */}
      <div className="mt-4 grid gap-4 sm:grid-cols-2 lg:grid-cols-4">
        <ReportMetric
          label="COGS"
          value={formatMoney(report.cogs)}
          icon={<Package size={18} strokeWidth={1.8} />}
        />

        <ReportMetric
          label="Delivery Cost"
          value={formatMoney(report.deliveryCost)}
          icon={<Truck size={18} strokeWidth={1.8} />}
          accent="negative"
        />

        <ReportMetric
          label="Operating Expenses"
          value={formatMoney(report.operatingExpenses)}
          icon={<Receipt size={18} strokeWidth={1.8} />}
          accent="negative"
        />

        <ReportMetric
          label="Net Profit"
          value={formatMoney(report.profit)}
          icon={<CircleDollarSign size={18} strokeWidth={1.8} />}
          accent={report.profit >= 0 ? "positive" : "negative"}
        />
      </div>

      {/* Operational summary */}
      <div className="mt-4 grid gap-4 sm:grid-cols-2 lg:grid-cols-4">
        <ReportMetric
          label="Completed Orders"
          value={report.orders.toLocaleString("en-BD")}
          icon={<ShoppingBag size={18} strokeWidth={1.8} />}
        />

        <ReportMetric
          label="Items Sold"
          value={report.itemsSold.toLocaleString("en-BD")}
          icon={<Package size={18} strokeWidth={1.8} />}
        />

        <ReportMetric
          label="Average Order"
          value={formatMoney(report.averageOrderValue)}
          icon={<BarChart3 size={18} strokeWidth={1.8} />}
        />

        <ReportMetric
          label="Profit Margin"
          value={`${profitMargin.toFixed(1)}%`}
          icon={<Percent size={18} strokeWidth={1.8} />}
          accent={profitMargin >= 0 ? "positive" : "negative"}
        />
      </div>

      {/* Financial report */}
      <div className="mt-8 grid gap-4 lg:grid-cols-2">
        <section className="border border-neutral-200 bg-white p-6">
          <h2 className="text-base font-semibold text-neutral-950">
            Financial Summary
          </h2>

          <div className="mt-4">
            <ReportRow
              label="Gross Sales"
              value={formatMoney(report.grossSales)}
            />

            <ReportRow
              label="Discounts"
              value={`− ${formatMoney(report.discountAmount)}`}
              negative={report.discountAmount > 0}
            />

            <ReportRow
              label="Net Sales"
              value={formatMoney(report.netSales)}
              strong
            />

            <ReportRow
              label="Shipping Revenue"
              value={`+ ${formatMoney(report.shippingRevenue)}`}
              positive={report.shippingRevenue > 0}
            />

            <div className="border-t border-neutral-200 pt-2">
              <ReportRow
                label="Total Revenue"
                value={formatMoney(report.revenue)}
                strong
              />
            </div>

            <ReportRow
              label="COGS"
              value={`− ${formatMoney(report.cogs)}`}
              negative={report.cogs > 0}
            />

            <ReportRow
              label="Delivery Cost"
              value={`− ${formatMoney(report.deliveryCost)}`}
              negative={report.deliveryCost > 0}
            />

            <ReportRow
              label="Operating Expenses"
              value={`− ${formatMoney(report.operatingExpenses)}`}
              negative={report.operatingExpenses > 0}
            />

            <div className="mt-2 border-t border-neutral-200 pt-2">
              <ReportRow
                label="Net Profit"
                value={formatMoney(report.profit)}
                strong
                positive={report.profit >= 0}
                negative={report.profit < 0}
              />
            </div>
          </div>
        </section>

        <ExpenseTable expenses={report.expenseBreakdown} />
      </div>

      {/* Product report */}
      <div className="mt-4">
        <ProductTable
          products={report.topProducts}
          totalRevenue={report.netSales}
        />
      </div>

      {/* Report note */}
      <div className="mt-4 border border-neutral-200 bg-neutral-50 p-5">
        <p className="text-sm font-medium text-neutral-700">Report basis</p>

        <p className="mt-1 text-sm leading-6 text-neutral-500">
          Financial figures are based on completed orders within the selected
          date range. Product COGS comes from immutable order snapshots, while
          operating expenses come from recorded expenses.
        </p>
      </div>
    </section>
  );
}

